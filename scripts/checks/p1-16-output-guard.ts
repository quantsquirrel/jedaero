// P1-16: LLM 출력 검증 — 조언·성향 라벨·전망이 통과하지 못하는가 (C8, C10)
// AI-3·AI-4·AI-7이 이 가드 하나를 공유한다. 여기가 뚫리면 세 지점이 동시에 뚫린다.
// "추천하지 마라"는 프롬프트로만 막지 않는다. 프롬프트는 지켜지지 않을 수 있고, 이건 지켜진다.
import { verifyFactualOutput } from '../../lib/ai/output-guard';

// 반드시 폐기되어야 하는 출력 (실제로 LLM이 낼 법한 문장들)
const MUST_BLOCK: [string, string][] = [
  ['조언', '최대 테마 비중이 60%입니다. 분산을 조금 늘려보세요.'],
  ['조언', '지출이 늘었습니다. 다음 달에는 줄이세요.'],
  ['조언', '채권 비중을 높이는 것을 고려해 보시면 좋겠습니다.'],
  ['조언', '지금 상태를 유지하시길 권장합니다.'],
  ['성향라벨', '배분이 공격적인 편입니다. 최대 비중은 60%입니다.'],
  ['성향라벨', '보수적 성향으로 보입니다.'],
  ['전망', '다음 주 국내 대형주는 상승할 가능성이 있습니다.'],
  ['전망', '금 가격 전망이 밝습니다.'],
  ['전망', '지금은 매수 시점입니다.'],
  ['전망', '손절 기준을 정해두는 편이 낫습니다.'],
];

// 반드시 통과해야 하는 출력 (사실 서술 + 열린 질문)
const MUST_PASS: string[] = [
  '최대 테마 비중 60%. 동기 코호트 중앙값은 22%입니다. 지난 6주간 비중을 한 번도 바꾸지 않으셨습니다. 이 배분은 어떤 생각으로 고르셨나요?',
  '이번 구간에 금·원자재가 1.8% 내렸고 배당이 0.6% 올랐습니다. 내 비중으로 가중하면 0.2% 내렸습니다.',
  '지금 35%가 예비대로 남아 있습니다. 이 병력을 아껴 두는 것은 기다림인가요, 미룸인가요?',
  '이번 주에 비중을 5%p 옮겼습니다. 그 판단의 근거는 다음 주에도 그대로일까요?',
];

let failed = 0;
for (const [kind, text] of MUST_BLOCK) {
  const v = verifyFactualOutput(text);
  if (v.ok) {
    console.log(`통과되면 안 되는 ${kind} 문장이 통과함: "${text}"`);
    failed += 1;
  }
}
for (const text of MUST_PASS) {
  const v = verifyFactualOutput(text);
  if (!v.ok) {
    console.log(`정상 사실 서술이 차단됨 (${v.reason}): "${text}"`);
    failed += 1;
  }
}
if (failed > 0) process.exit(1);
console.log(`차단 대상 ${MUST_BLOCK.length}건 전부 폐기, 사실 서술 ${MUST_PASS.length}건 전부 통과`);
